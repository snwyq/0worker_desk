export const hasLiuHe = (a, b) => {
  const liuHePairs = [
    ['子', '丑'], ['寅', '亥'], ['卯', '戌'], ['辰', '酉'], ['巳', '申'], ['午', '未'],
  ];
  return liuHePairs.some(([lhA, lhB]) =>
    (a === lhA && b === lhB) || (a === lhB && b === lhA)
  );
};

